package com.library.common;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.Generated;
import java.time.OffsetDateTime;
import java.util.UUID;

/**
 * Base abstract class for all persistent entities in the system.
 * Provides a standardized UUID primary key and automated auditing fields.
 * This entity offloads timestamp management to the database level (PostgreSQL)
 * using {@link Generated} to ensure the application stays in sync with
 * database-side triggers and defaults.
 */
@MappedSuperclass
@Getter
@Setter
public abstract class BaseEntity {

    /**
     * Unique identifier for the entity.
     * Generated by the application using a UUID
     * strategy before the entity is persisted.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /**
     * The timestamp when the record was first created.
     * Managed by the database via DEFAULT CURRENT_TIMESTAMP.
     * This field is read-only for the application.
     */
    @Generated
    @Column(name = "created_at", insertable = false, updatable = false)
    private OffsetDateTime createdAt;

    /**
     * The timestamp when the record was last modified.
     * Managed by the database via a trigger on every update.
     * This field is read-only for the application.
     */
    @Generated
    @Column(name = "updated_at", insertable = false, updatable = false)
    private OffsetDateTime updatedAt;

    /**
     * Flag indicating if the record has been soft-deleted.
     * Defaults to false.
     */
    @Column(nullable = false)
    private boolean deleted = false;
}